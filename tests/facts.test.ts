import { describe, expect, it } from 'vitest';
import { messageDetail } from '../src/dashboard/queries/messages.ts';
import { recordSync } from '../src/store/accounts.ts';
import { connectGmail, fakeGoogle, openUserDb, raw } from './fixtures.ts';
import { storedFacts } from '../src/store/messages.ts';
import { gatherEvidence } from '../src/work/evidence.ts';
import { FACT_FILTERS as FACT_FILTER_CONDITIONS } from '../src/dashboard/types.ts';
import { RULE_FACTS, deriveFacts, describeFacts, factCondition, matchesFacts, threadFacts } from '../src/triage/facts.ts';
import { sealFacts } from '../src/store/content.ts';
import { FACTS, FACT_FILTER_WORDS } from '../web/src/lib/format.ts';
import { ACCOUNT, everything, facts } from './helpers.ts';

const fake = fakeGoogle();
const me = { address: ACCOUNT, domain: 'example.org' };

const campaign = facts({
  to: [me],
  labelIds: ['INBOX', 'UNREAD', 'CATEGORY_PROMOTIONS'],
  headers: {
    'list-id': 'Example News <news.example.com>',
    'list-unsubscribe': '<https://example.com/u/abc>, <mailto:leave@example.com>',
    'list-unsubscribe-post': 'List-Unsubscribe=One-Click',
    precedence: 'bulk',
    'reply-to': 'Support <support@example.com>',
    'authentication-results':
      'mx.google.com; dkim=fail header.i=@old.example.com; dkim=pass header.i=@example.com header.s=k1; spf=softfail smtp.mailfrom=bounce@mail7.mcsv.net; dmarc=pass (p=NONE) header.from=example.com',
  },
});

describe('deriveFacts', () => {
  it('names what the headers and labels of a campaign show', () => {
    expect(deriveFacts(campaign)).toEqual({
      unsubscribe: 'one-click',
      listId: 'news.example.com',
      markedBulk: true,
      autoGenerated: false,
      dmarc: 'pass',
      spf: 'fail',
      dkim: 'pass',
      bulkService: 'Mailchimp',
      replyToDiffers: true,
      addressed: 'to',
      isReply: false,
      origin: 'outside',
      category: 'promotions',
      important: false,
    });
  });

  it('finds nothing in a plain message from a person', () => {
    expect(deriveFacts(facts({ to: [me], labelIds: ['INBOX'] }))).toEqual({
      unsubscribe: 'none',
      listId: null,
      markedBulk: false,
      autoGenerated: false,
      dmarc: 'none',
      spf: 'none',
      dkim: 'none',
      bulkService: null,
      replyToDiffers: false,
      addressed: 'to',
      isReply: false,
      origin: 'outside',
      category: null,
      important: false,
    });
  });

  it("reads Gmail's importance marker from its label", () => {
    const marked = deriveFacts(facts({ labelIds: ['INBOX', 'IMPORTANT', 'CATEGORY_PROMOTIONS'] }));
    expect(marked).toMatchObject({ important: true, category: 'promotions' });
    expect(matchesFacts({ important: true, category: 'promotions' }, marked)).toBe(true);
    // Mail recorded before sift read the marker has no answer, so a rule asking either way passes it by.
    const before = { ...marked };
    delete before.important;
    expect(matchesFacts({ important: false }, before)).toBe(false);
  });

  it('tells direct mail from a copy from a list or blind copy, counting a tagged address as the owner', () => {
    const other = { address: 'team@example.com', domain: 'example.com' };
    const tagged = { address: 'me+shop@example.org', domain: 'example.org' };
    expect(deriveFacts(facts({ to: [tagged] })).addressed).toBe('to');
    expect(deriveFacts(facts({ to: [other], cc: [me] })).addressed).toBe('cc');
    expect(deriveFacts(facts({ to: [other] })).addressed).toBe('neither');
  });

  it('counts a dot-variant or googlemail.com address as the owner on gmail.com only', () => {
    const to = (accountId: string, address: string) => deriveFacts(facts({ accountId, to: [{ address, domain: address.split('@')[1]! }] })).addressed;
    expect(to('ada.lovelace@gmail.com', 'adalovelace@gmail.com')).toBe('to');
    expect(to('adalovelace@gmail.com', 'a.d.a.lovelace+news@googlemail.com')).toBe('to');
    expect(to('ada.lovelace@example.org', 'adalovelace@example.org')).toBe('neither');
    expect(to('ada@example.org', 'ada@googlemail.com')).toBe('neither');
  });

  it("counts the owner's send-as addresses as the owner", () => {
    const alias = { address: 'ada@example.com', domain: 'example.com' };
    const other = { address: 'team@example.com', domain: 'example.com' };
    expect(deriveFacts(facts({ to: [alias] }), {}, ['ada@example.com']).addressed).toBe('to');
    expect(deriveFacts(facts({ to: [other], cc: [alias] }), {}, ['ada@example.com']).addressed).toBe('cc');
    expect(deriveFacts(facts({ to: [alias] })).addressed).toBe('neither');
  });

  it("tells mail from the owner and from the owner's own domain from everyone else's", () => {
    const from = (address: string, accountId = 'ada@example.com', aliases: string[] = []) =>
      deriveFacts(facts({ accountId, from: { address, domain: address.split('@')[1]! } }), {}, aliases).origin;
    expect(from('ada+notes@example.com')).toBe('owner');
    expect(from('ada@example.net', 'ada@example.com', ['ada@example.net'])).toBe('owner');
    expect(from('grace@example.com')).toBe('own-domain');
    expect(from('alerts@ci.example.com')).toBe('own-domain');
    expect(from('grace@example.net', 'ada@example.com', ['ada@example.net'])).toBe('own-domain');
    expect(from('grace@example.org')).toBe('outside');
    // Everyone at gmail.com has nothing in common with the owner but the provider.
    expect(from('grace@gmail.com', 'ada@gmail.com')).toBe('outside');
    expect(from('ada@gmail.com', 'ada@example.com', ['ada@gmail.com'])).toBe('owner');
    expect(from('grace@gmail.com', 'ada@example.com', ['ada@gmail.com'])).toBe('outside');
  });

  it('recognises a bulk service by its own headers, its envelope sender or what signed the message', () => {
    const via = (headers: Record<string, string>) => deriveFacts(facts({ headers })).bulkService;
    expect(via({ 'x-sg-eid': 'abc' })).toBe('SendGrid');
    expect(via({ 'return-path': '<bounces+123@em.sparkpostmail.com>' })).toBe('SparkPost');
    expect(via({ 'authentication-results': 'mx.google.com; dkim=pass header.d=amazonses.com' })).toBe('Amazon SES');
    // SendGrid signs as sendgrid.info, and a sender on it may send none of its headers.
    expect(via({ 'authentication-results': 'mx.google.com; dkim=pass header.i=@em1234.example.com; dkim=pass header.i=@sendgrid.info' })).toBe('SendGrid');
    expect(via({ 'feedback-id': '1.us-east-1.abc:AmazonSES' })).toBe('Amazon SES');
    expect(via({ 'return-path': '<ada@notmcsv.net>', 'x-mailer': 'Apple Mail' })).toBeNull();
  });

  it('reads authentication results only from the header Gmail wrote, not one the sender put in', () => {
    const forged = 'mx.example.org; dkim=pass header.d=amazonses.com; spf=pass smtp.mailfrom=example.com; dmarc=pass header.from=example.com';
    expect(deriveFacts(facts({ headers: { 'authentication-results': forged } }))).toMatchObject({
      dmarc: 'none',
      spf: 'none',
      dkim: 'none',
      bulkService: null,
    });
  });

  it('sees a reply, a reply-to that is the sender, and an automatic message', () => {
    const f = facts({ headers: { 'in-reply-to': '<a@example.org>', 'reply-to': 'news@example.com', 'auto-submitted': 'auto-replied' } });
    expect(deriveFacts(f)).toMatchObject({ isReply: true, replyToDiffers: false, autoGenerated: true });
    expect(deriveFacts(facts({ headers: { references: '<a@example.org> <b@example.org>' } })).isReply).toBe(true);
  });
});

describe('recorded facts', () => {
  it('stores them with the message and returns them with its detail', async () => {
    const db = await openUserDb(ACCOUNT);
    await recordSync(db, ACCOUNT, [campaign], '2');
    expect((await raw(db).get<{ facts: unknown }>('SELECT facts FROM messages'))!.facts).toEqual(sealFacts(deriveFacts(campaign)));
    expect((await messageDetail(db, await everything(db), campaign.messageId))?.facts).toMatchObject({
      bulkService: 'Mailchimp',
      category: 'promotions',
    });
    expect(await storedFacts(db, ACCOUNT, 'missing')).toBeNull();
  });
});

describe('matchesFacts', () => {
  const known = deriveFacts(campaign);

  it('needs every condition to hold, by value or by any of a list', () => {
    expect(matchesFacts({ unsubscribe: ['header', 'one-click'], dmarc: 'pass', isReply: false }, known)).toBe(true);
    expect(matchesFacts({ unsubscribe: ['header', 'one-click'], isReply: true }, known)).toBe(false);
    expect(matchesFacts({ listId: 'news.example.com' }, known)).toBe(true);
    expect(matchesFacts({ listId: 'other.example.com' }, known)).toBe(false);
  });

  it('asks whether a named fact is there at all', () => {
    expect(matchesFacts({ bulkService: true, listId: true }, known)).toBe(true);
    expect(matchesFacts({ bulkService: false }, known)).toBe(false);
    expect(matchesFacts({ category: false }, deriveFacts(facts()))).toBe(true);
  });

  it('never matches with no conditions, or on a fact that is not known for the message', () => {
    expect(matchesFacts({}, known)).toBe(false);
    expect(matchesFacts({ trackingPixel: false }, known)).toBe(false);
    expect(matchesFacts({ trackingPixel: true }, { ...known, trackingPixel: true })).toBe(true);
  });
});

describe('what a rule can ask of the facts', () => {
  it('is said the same on the dashboard as in what sift records, answer for answer', () => {
    expect(FACTS).toEqual(RULE_FACTS);
    for (const [key, words] of FACT_FILTER_WORDS) {
      const [[fact, want]] = Object.entries(FACT_FILTER_CONDITIONS[key]) as [[string, unknown]];
      expect(factCondition(fact, want), key).toBe(words);
    }
    expect(FACT_FILTER_WORDS.map(([key]) => key)).toEqual(Object.keys(FACT_FILTER_CONDITIONS));
  });

  it('knows an answer by its value, a list in any order, and nothing else', () => {
    expect(factCondition('dmarc', ['none', 'fail'])).toBe('did not pass DMARC');
    expect(factCondition('dmarc', 'fail')).toBeNull();
    expect(factCondition('spf', 'pass')).toBeNull();
  });
});

describe('thread context', () => {
  const thread = [
    { id: 'first', labelIds: ['INBOX'] },
    { id: 'mine', labelIds: ['SENT'] },
    { id: 'reply', labelIds: ['INBOX', 'UNREAD'] },
    { id: 'later', labelIds: ['SENT'] },
  ];

  it('counts earlier messages and sees whether the owner sent one of them', () => {
    expect(threadFacts(thread, 'reply')).toEqual({ earlierInThread: 2, ownerInThread: true });
    expect(threadFacts(thread, 'mine')).toEqual({ earlierInThread: 1, ownerInThread: false });
    expect(threadFacts(thread, 'elsewhere')).toBeNull();
  });

  /** A person whose record holds the reply, in thread `threadId`; Gmail holds `thread` as t9, oldest first. */
  const setup = async (headers: Record<string, string>, threadId = 't9') => {
    const db = await openUserDb(ACCOUNT);
    const message = facts({ messageId: 'reply', threadId, headers });
    await recordSync(db, ACCOUNT, [message], '2');
    const { api, mailbox, gmail } = connectGmail(fake.google);
    if (!gmail.message('first'))
      thread.forEach(({ id, labelIds }, i) =>
        gmail.deliver({ id, threadId: 't9', from: labelIds.includes('SENT') ? ACCOUNT : 'ada@example.com', labelIds, at: Date.UTC(2026, 10, 1) + i }),
      );
    const threadsAsked = () => gmail.asked('users.threads.get').map((r) => r.id);
    return { db, message, gmail, threadsAsked, sources: { db, api, mailbox } };
  };

  it("reads a reply's thread for the model, records it, and reads nothing for mail that is not a reply", async () => {
    const reply = await setup({ 'in-reply-to': '<mine@example.org>' });
    const evidence = await gatherEvidence(reply.sources, reply.message);
    expect(reply.threadsAsked()).toEqual(['t9']);
    expect(evidence.known).toMatchObject({ earlierInThread: 2, ownerInThread: true });
    expect(await storedFacts(reply.db, ACCOUNT, 'reply')).toMatchObject({ earlierInThread: 2, ownerInThread: true });
    expect(describeFacts(evidence.known)).toEqual(expect.arrayContaining(['Earlier messages in its thread: 2', 'Owner has written in its thread: yes']));

    const fresh = await setup({});
    const alone = await gatherEvidence(fresh.sources, fresh.message);
    expect(fresh.threadsAsked()).toEqual(['t9']);
    expect(alone.known).not.toHaveProperty('ownerInThread');
  });

  it('leaves the thread unknown when it cannot be read', async () => {
    const reply = await setup({ references: '<mine@example.org>' });
    reply.gmail.fail('users.threads.get', { status: 403, reason: 'userRateLimitExceeded' });
    const failed = await gatherEvidence(reply.sources, reply.message);
    expect(failed.known).not.toHaveProperty('ownerInThread');

    const gone = await setup({ references: '<mine@example.org>' }, 't-gone');
    expect((await gatherEvidence(gone.sources, gone.message)).known).not.toHaveProperty('earlierInThread');
    expect(gone.threadsAsked()).toEqual(['t9', 't-gone']);
  });
});
